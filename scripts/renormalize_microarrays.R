script<-sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE))
source(file.path(dirname(script),'bootstrap.R'))
if(length(commandArgs(TRUE)))stop('No arguments; set SALT_DATA_ROOT, SALT_NORMALIZED_ROOT and SALT_NORMALIZATION_OUTPUT_ROOT')
source_root<-Sys.getenv('SALT_DATA_ROOT');destination<-Sys.getenv('SALT_NORMALIZED_ROOT');output<-Sys.getenv('SALT_NORMALIZATION_OUTPUT_ROOT')
if(any(!nzchar(c(source_root,destination,output))))stop('Set all three external roots')
source_root<-normalizePath(source_root,mustWork=TRUE);destination<-normalizePath(destination,mustWork=FALSE)
output<-normalizePath(output,mustWork=FALSE)
inside<-function(path,parent)identical(path,parent)||startsWith(path,paste0(parent,'/'))
if(inside(output,source_root)||inside(source_root,output)||inside(output,destination)||inside(destination,output)||inside(output,project_root))
 stop('Keep original inputs, normalized inputs, code and output roots separate')
dir.create(output,recursive=TRUE,showWarnings=FALSE)
code_paths<-source_files(project_root)
code_before<-setNames(vapply(code_paths,function(p)digest::digest(file=p,algo='sha256'),''),substring(code_paths,nchar(project_root)+2L))
source<-normalization_sources(source_root)
old_ids<-c('microarray_root','microarray_shoot','microarray_genotype')
old_paths<-vapply(old_ids,function(id)input_specs[[id]]$path,'')
source$input_paths<-c(source$input_paths,setNames(file.path(source_root,old_paths),old_paths))
input_hash<-setNames(vapply(source$input_paths,function(p)digest::digest(file=p,algo='sha256'),''),names(source$input_paths))
result<-normalization_variants(source)
write_table(source$feature_qc,file.path(output,'feature_QC.csv'))
write_table(result$metrics,file.path(output,'normalization_diagnostics.csv'))
write_table(normalization_comparison(result,source_root),file.path(output,'supplied_normalization_comparison.csv'))
samples<-do.call(rbind,lapply(names(result$matrices),function(group){z<-result$matrices[[group]];data.frame(group=group,order=seq_len(ncol(z$methods$quantile)),sample=colnames(z$methods$quantile),condition=z$groups)}))
write_table(samples,file.path(output,'normalization_samples.csv'))
normalization_diagnostics_figure(result,file.path(output,'normalization_distributions.pdf'))
normalized<-normalization_prepare_root(source_root,destination,result)
stopifnot(identical(input_hash,setNames(vapply(source$input_paths,function(p)digest::digest(file=p,algo='sha256'),''),names(source$input_paths))))
revision<-system2('git',c('-C',shQuote(project_root),'rev-parse','HEAD'),stdout=TRUE)
stopifnot(identical(code_before,setNames(vapply(code_paths,function(p)digest::digest(file=p,algo='sha256'),''),names(code_before))))
provenance<-list(method=normalization_settings(),generated_UTC=format(Sys.time(),tz='UTC',usetz=TRUE),git_revision=revision,
 source_root=source_root,input_sha256=input_hash,code_sha256=code_before,
 normalized_relative_paths=setNames(substring(normalized,nchar(destination)+2L),names(normalized)),
 normalized_sha256=setNames(vapply(normalized,function(p)digest::digest(file=p,algo='sha256'),''),names(normalized)),
 scope='RNA only; unchanged proteomics and other files link to original inputs',
 full_FE_exports=sum(source$feature_qc$full_FE),reduced_exports=sum(!source$feature_qc$full_FE),
 limma_version=as.character(packageVersion('limma')),R_version=R.version.string)
dput(provenance,file=file.path(destination,'NORMALIZATION_PROVENANCE.R'))
diagnostic_paths<-list.files(output,full.names=TRUE)
provenance$diagnostic_sha256<-setNames(vapply(diagnostic_paths,function(p)digest::digest(file=p,algo='sha256'),''),basename(diagnostic_paths))
dput(provenance,file=file.path(output,'provenance.R'))
writeLines(capture.output(sessionInfo()),file.path(output,'sessionInfo.txt'))
writeLines('Complete; normalized matrices and unchanged input hashes verified.',file.path(output,'RUN_COMPLETE'))
message('Quantile-normalized external input root ready: ',destination)
